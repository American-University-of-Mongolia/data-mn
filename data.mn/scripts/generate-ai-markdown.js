/**
 * Generate AI-Friendly Markdown Pages
 *
 * Creates markdown versions of data pages for AI agents.
 * Reads Excel files and converts them to markdown tables.
 *
 * Usage: node scripts/generate-ai-markdown.js
 * Runs after: astro build (writes to dist/)
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';
import XLSX from 'xlsx';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Configuration
const LANGUAGES = ['en', 'mn'];
const MDX_BASE = path.resolve(__dirname, '../src/data/data');
const DATASETS_DIR = path.resolve(__dirname, '../public/datasets');
const DIST_DIR = path.resolve(__dirname, '../dist');
const MAX_ROWS = 100;
const SITE_URL = 'https://data.mn';

// Sheet name mapping (language -> possible sheet names)
const SHEET_NAMES = {
  en: ['English', 'EN', 'Sheet1'],
  mn: ['Mongolian', 'MN', 'Sheet2'],
};

// Labels in each language
const LABELS = {
  en: {
    overview: 'Overview',
    category: 'Category',
    lastUpdated: 'Last Updated',
    source: 'Source',
    tags: 'Tags',
    data: 'Data',
    truncatedNote: (shown, total) => `*Showing first ${shown} of ${total} rows. Full dataset available for download.*`,
    downloads: 'Downloads',
    downloadCSV: 'Download as CSV',
    downloadExcel: 'Download as Excel',
    relatedPages: 'Related Pages',
    englishVersion: 'English version',
    mongolianVersion: 'Mongolian version',
    footer: "Generated by Data.mn - Mongolia's Open Data Platform",
  },
  mn: {
    overview: 'Товч мэдээлэл',
    category: 'Ангилал',
    lastUpdated: 'Шинэчилсэн огноо',
    source: 'Эх сурвалж',
    tags: 'Түлхүүр үг',
    data: 'Өгөгдөл',
    truncatedNote: (shown, total) => `*Нийт ${total} мөрөөс эхний ${shown}-г харуулж байна. Бүрэн өгөгдлийг татаж авах боломжтой.*`,
    downloads: 'Татах',
    downloadCSV: 'CSV татах',
    downloadExcel: 'Excel татах',
    relatedPages: 'Холбоотой хуудсууд',
    englishVersion: 'Англи хувилбар',
    mongolianVersion: 'Монгол хувилбар',
    footer: 'Data.mn - Монголын Нээлттэй Мэдээллийн Платформ',
  },
};

/**
 * Find the correct sheet for a language
 */
function findSheet(workbook, lang) {
  const possibleNames = SHEET_NAMES[lang];
  for (const name of possibleNames) {
    if (workbook.SheetNames.includes(name)) {
      return workbook.Sheets[name];
    }
  }
  // Fallback to first sheet
  return workbook.Sheets[workbook.SheetNames[0]];
}

/**
 * Convert worksheet to array of arrays
 */
function sheetToArray(sheet) {
  return XLSX.utils.sheet_to_json(sheet, { header: 1 });
}

/**
 * Convert array of arrays to markdown table
 */
function toMarkdownTable(data, maxRows = MAX_ROWS) {
  if (!data || data.length === 0) return '';

  const headers = data[0];
  const rows = data.slice(1, maxRows + 1);
  const totalRows = data.length - 1; // Exclude header

  // Build header row
  let table = '| ' + headers.map((h) => String(h ?? '')).join(' | ') + ' |\n';
  table += '| ' + headers.map(() => '---').join(' | ') + ' |\n';

  // Build data rows
  for (const row of rows) {
    const cells = headers.map((h, i) => {
      const val = row[i];
      if (val === null || val === undefined) return '';
      if (typeof val === 'number') {
        // Don't format years with commas (4-digit numbers in year-like columns)
        const headerLower = String(h).toLowerCase();
        const isYearColumn = headerLower === 'year' || headerLower === 'он' || headerLower.includes('year');
        const isYear = isYearColumn && val >= 1900 && val <= 2100;

        if (isYear) {
          return String(val);
        }
        // Format other numbers with commas for readability
        return val.toLocaleString('en-US', { maximumFractionDigits: 2 });
      }
      return String(val);
    });
    table += '| ' + cells.join(' | ') + ' |\n';
  }

  return { table, shown: rows.length, total: totalRows };
}

/**
 * Generate markdown content for a data page
 */
function generateMarkdown(frontmatter, excelData, lang, slug) {
  const t = LABELS[lang];
  const otherLang = lang === 'en' ? 'mn' : 'en';

  let md = `# ${frontmatter.title}\n\n`;
  md += `> ${frontmatter.excerpt}\n\n`;

  // Overview section
  md += `## ${t.overview}\n\n`;

  if (frontmatter.category) {
    md += `- **${t.category}:** ${frontmatter.category}\n`;
  }

  const dateStr = frontmatter.dataDate || frontmatter.publishDate;
  if (dateStr) {
    const date = dateStr instanceof Date ? dateStr.toISOString().split('T')[0] : dateStr;
    md += `- **${t.lastUpdated}:** ${date}\n`;
  }

  if (frontmatter.source) {
    const sourceUrl = frontmatter.source.url || '';
    const sourceNote = frontmatter.source.tableId ? ` (Table ID: ${frontmatter.source.tableId})` : '';
    md += `- **${t.source}:** [${frontmatter.source.name}](${sourceUrl})${sourceNote}\n`;
  }

  if (frontmatter.tags && frontmatter.tags.length > 0) {
    md += `- **${t.tags}:** ${frontmatter.tags.join(', ')}\n`;
  }

  md += '\n';

  // Data section
  if (excelData && excelData.length > 1) {
    md += `## ${t.data}\n\n`;
    const { table, shown, total } = toMarkdownTable(excelData, MAX_ROWS);
    md += table;

    if (shown < total) {
      md += `\n${t.truncatedNote(shown, total)}\n`;
    }
    md += '\n';
  }

  // Downloads section
  if (frontmatter.dataFiles && frontmatter.dataFiles.length > 0) {
    md += `## ${t.downloads}\n\n`;
    for (const file of frontmatter.dataFiles) {
      const format = (file.format || '').toLowerCase();
      const label = format === 'csv' ? t.downloadCSV : t.downloadExcel;
      md += `- [${label}](${SITE_URL}${file.path})\n`;
    }
    md += '\n';
  }

  // Related pages (cross-language links)
  md += `## ${t.relatedPages}\n\n`;
  md += `- [${t.englishVersion}](${SITE_URL}/en/data/${slug})\n`;
  md += `- [${t.mongolianVersion}](${SITE_URL}/mn/data/${slug})\n`;
  md += '\n';

  // Footer
  md += `---\n`;
  md += `*${t.footer}*  \n`;
  md += `*URL: ${SITE_URL}/${lang}/data/${slug}*\n`;

  return md;
}

/**
 * Find the Excel file for a given slug
 */
function findExcelFile(slug) {
  // Try common naming patterns
  const patterns = [`${slug}.xlsx`, `${slug}.xls`];

  for (const pattern of patterns) {
    const filePath = path.join(DATASETS_DIR, pattern);
    if (fs.existsSync(filePath)) {
      return filePath;
    }
  }

  return null;
}

/**
 * Process a single MDX file
 */
function processFile(lang, mdxPath) {
  const filename = path.basename(mdxPath);
  const slug = filename.replace(/\.mdx?$/, '');

  // Read and parse MDX frontmatter
  const mdxContent = fs.readFileSync(mdxPath, 'utf-8');
  const { data: frontmatter } = matter(mdxContent);

  // Skip drafts
  if (frontmatter.draft === true) {
    return { skipped: true, reason: 'draft' };
  }

  // Find Excel file
  const excelPath = findExcelFile(slug);
  let excelData = null;

  if (excelPath) {
    try {
      const workbook = XLSX.readFile(excelPath);
      const sheet = findSheet(workbook, lang);
      excelData = sheetToArray(sheet);
    } catch (err) {
      console.warn(`  ⚠ Excel read error for ${slug}: ${err.message}`);
    }
  } else {
    console.warn(`  ⚠ No Excel file found for ${slug}`);
  }

  // Generate markdown
  const markdown = generateMarkdown(frontmatter, excelData, lang, slug);

  // Output path - matches Astro's output structure
  const outputDir = path.join(DIST_DIR, lang, 'data', slug);
  const outputPath = path.join(outputDir, 'index.md');

  // Ensure directory exists
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Write markdown file
  fs.writeFileSync(outputPath, markdown, 'utf-8');

  return { success: true, slug, outputPath };
}

/**
 * Main function
 */
async function main() {
  console.log('📝 Generating AI-friendly markdown files...\n');

  // Check if dist directory exists
  if (!fs.existsSync(DIST_DIR)) {
    console.error('❌ dist/ directory not found. Run "astro build" first.');
    process.exit(1);
  }

  let successCount = 0;
  let skipCount = 0;
  let errorCount = 0;

  for (const lang of LANGUAGES) {
    const langDir = path.join(MDX_BASE, lang);

    if (!fs.existsSync(langDir)) {
      console.warn(`⚠ Language directory not found: ${langDir}`);
      continue;
    }

    const mdxFiles = fs.readdirSync(langDir).filter((f) => f.endsWith('.mdx'));
    console.log(`Processing ${mdxFiles.length} ${lang.toUpperCase()} pages...`);

    for (const file of mdxFiles) {
      const mdxPath = path.join(langDir, file);

      try {
        const result = processFile(lang, mdxPath);

        if (result.skipped) {
          skipCount++;
        } else if (result.success) {
          console.log(`  ✓ ${lang}/${result.slug}`);
          successCount++;
        }
      } catch (error) {
        console.error(`  ✗ ${file}: ${error.message}`);
        errorCount++;
      }
    }
  }

  console.log(`\n✨ Done! ${successCount} generated, ${skipCount} skipped, ${errorCount} failed`);
}

// Run
main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
